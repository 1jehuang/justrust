//! Generate the uppercase data header using the acceptance oracle toolchain.
//! Unicode version is recorded in the output. Rows are 25 ASCII bytes:
//! source (6 hex), length (1), three values (6 hex each). Length zero encodes
//! a simple mapping range: first uppercase scalar, final source, source step.
//! Other lengths encode one to three uppercase scalars.
fn main() {
    let mut mappings = Vec::new();
    for value in 0..=0x10ffffu32 {
        let Some(c) = char::from_u32(value) else {
            continue;
        };
        let upper: Vec<u32> = c.to_uppercase().map(u32::from).collect();
        if upper.as_slice() != [value] {
            mappings.push((value, upper));
        }
    }
    let mut table = String::new();
    let mut count = 0;
    let mut i = 0;
    while i < mappings.len() {
        let (source, upper) = &mappings[i];
        let mut end = i;
        let mut step = 0;
        if upper.len() == 1 && i + 1 < mappings.len() {
            step = mappings[i + 1].0 - source;
            if step <= 2 {
                while end + 1 < mappings.len() {
                    let (next, mapped) = &mappings[end + 1];
                    if mapped.len() != 1
                        || *next - mappings[end].0 != step
                        || mapped[0] as i64 - *next as i64 != upper[0] as i64 - *source as i64
                    {
                        break;
                    }
                    end += 1;
                }
            }
        }
        use std::fmt::Write;
        if end > i {
            write!(
                table,
                "{source:06x}0{:06x}{:06x}{step:06x}",
                upper[0], mappings[end].0
            )
            .unwrap();
        } else {
            write!(table, "{source:06x}{}", upper.len()).unwrap();
            for j in 0..3 {
                write!(table, "{:06x}", upper.get(j).copied().unwrap_or(0)).unwrap();
            }
        }
        count += 1;
        i = end + 1;
    }
    println!(
        "// Uppercase mappings generated by tools/generate_unicode_uppercase.rs.\n// Unicode {:?}. 25-byte rows: source, length, three scalars or range (upper, end, step).\nconst UPPERCASE_ROWS: usize = {count}usize;\nconst UPPERCASE_DATA: &str = \"{table}\";",
        std::char::UNICODE_VERSION
    );
}
