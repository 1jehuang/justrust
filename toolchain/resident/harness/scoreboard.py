#!/usr/bin/env python3
"""Runs every target in targets.json through difftest and writes scoreboard.json + SCOREBOARD.md.

Exit code is non-zero when any target's behaviour differs from rustc, or when coverage drops
below the committed scoreboard (pass --update to accept the new numbers).
"""
import json, os, subprocess, sys, tempfile

# ra-jit computes layouts with rust-analyzer's copy of rustc_abi, so everything it links against
# has to come from the rustc that copy was taken from.
os.environ.setdefault("RUSTUP_TOOLCHAIN", open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "toolchain")).read().strip())

HERE = os.path.dirname(os.path.abspath(__file__))
BOARD = os.path.join(HERE, "scoreboard.json")


def run(name, target):
    out = tempfile.mktemp(suffix=".json")
    if "tests" in target:
        # Windows starts no script by its first line.
        shell = ["sh"] if os.name == "nt" else []
        subprocess.run([*shell, os.path.join(HERE, "vendor.sh"), target["tests"]], check=True)
        directory = os.path.join(HERE, "vendor", target["tests"].rsplit("-", 1)[0])
        cmd = [sys.executable, os.path.join(HERE, "cratetest.py"), directory, "--bisect", "--json", out]
    else:
        cmd = [sys.executable, os.path.join(HERE, "difftest.py"), os.path.join(HERE, target["workspace"]),
               "--bin", target["bin"], "--bisect", "--json", out]
        for crate in target["crates"]:
            cmd += ["--crate", crate]
    proc = subprocess.run(cmd, capture_output=True, text=True)
    if not os.path.exists(out):
        return {"match": False, "crash": proc.stdout[-500:] + proc.stderr[-500:], "crates": {}}
    return json.load(open(out))


def markdown(board):
    lines = ["# ra-jit scoreboard", "", "Generated by `harness/scoreboard.py`. Do not edit.", "",
             "| Target | Crate | Matches rustc | Compiled by ra-jit | Extra instances | Cold codegen |",
             "|---|---|---|---|---|---|"]
    reasons = {}
    for name, result in board.items():
        verdict = "yes" if result["match"] else "**NO**"
        if result["match"] and "tests_run" in result:
            verdict = f"yes ({result['tests_run']} tests)"
        for crate, c in result["crates"].items():
            share = f"{c['compiled']} / {c['roots']}" + (f" ({100 * c['compiled'] // c['roots']}%)" if c["roots"] else "")
            lines.append(f"| {name} | {crate} | {verdict} | {share} | {c['instances']} | {c['codegen_ms']:.0f} ms |")
            for reason, n in c["skipped"].items():
                reasons[reason] = reasons.get(reason, 0) + n
        for culprit in result.get("culprits", []):
            lines.append(f"| {name} | | miscompiled `{culprit['function']}` | {culprit['symptom']} | | |")
    lines += ["", "## Why functions were left to rustc", "", "| Reason | Functions |", "|---|---|"]
    lines += [f"| {reason} | {n} |" for reason, n in sorted(reasons.items(), key=lambda kv: -kv[1])]
    return "\n".join(lines) + "\n"


def main():
    targets = json.load(open(os.path.join(HERE, "targets.json")))
    old = json.load(open(BOARD)) if os.path.exists(BOARD) else {}
    board, failed = {}, False
    for name, target in targets.items():
        board[name] = result = run(name, target)
        print(f"{name}: {'match' if result['match'] else 'MISMATCH'}")
        failed |= not result["match"]
        for crate, c in result["crates"].items():
            before = old.get(name, {}).get("crates", {}).get(crate, {}).get("compiled", 0)
            print(f"  {crate}: {c['compiled']}/{c['roots']} (was {before})")
            if c["compiled"] < before:
                print("  ^ coverage regression")
                failed |= "--update" not in sys.argv
    if "--update" in sys.argv or not old:
        json.dump(board, open(BOARD, "w"), indent=1, sort_keys=True)
        open(os.path.join(HERE, "SCOREBOARD.md"), "w").write(markdown(board))
    sys.exit(1 if failed else 0)


if __name__ == "__main__":
    main()
