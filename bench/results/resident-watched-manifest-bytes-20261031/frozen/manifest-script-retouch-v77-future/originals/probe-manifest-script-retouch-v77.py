def sha(data):
    return hashlib.sha256(data).hexdigest()


def snapshot(path, include_bytes=True):
    st = path.stat()
    result = {'path': str(path), 'dev': st.st_dev, 'ino': st.st_ino,
              'mode': st.st_mode, 'size': st.st_size, 'mtime_ns': st.st_mtime_ns,
              'atime_ns': st.st_atime_ns, 'ctime_ns': st.st_ctime_ns}
    if path.is_file():
        data = path.read_bytes()
        result['sha256'] = sha(data)
        if include_bytes:
            result['bytes_base64'] = base64.b64encode(data).decode('ascii')
    return result


def processes(home):
    """Runtime-only read-only PID/starttime/exe evidence scoped to this private root."""
    found = []
    for proc in Path('/proc').iterdir():
        if not proc.name.isdigit():
            continue
        try:
            environ = (proc / 'environ').read_bytes().split(b'\0')
            if os.fsencode('BLAZE_HOME=' + str(home)) not in environ:
                continue
            exe = (proc / 'exe').resolve(strict=True)
            found.append({'pid': int(proc.name), 'stat': (proc / 'stat').read_text(),
                          'exe': str(exe), 'exe_sha256': sha(exe.read_bytes()),
                          'cmdline_base64': base64.b64encode((proc / 'cmdline').read_bytes()).decode('ascii')})
        except (OSError, ValueError):
            continue
    return sorted(found, key=lambda row: row['pid'])


def evidence(output, label, env):
    home = Path(env['BLAZE_HOME'])
    dest = output / (label + '-worker-evidence')
    dest.mkdir()
    saved = []
    for path in sorted(home.rglob('*')):
        if path.is_file() and (path.name in ('log', 'daemon.log', 'pid') or path.suffix == '.pid'):
            target = dest / path.relative_to(home)
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(path.read_bytes())
            saved.append(snapshot(target))
    return {'processes': processes(home), 'files': saved}


def run_arm(args, arm, toolchain, engine_before):
    output = args.output / arm
    output.mkdir()
    source = output / 'source'
    (source / 'src').mkdir(parents=True)
    for name, data in FILES.items():
        m.durable(source / name, data, exclusive=True)
    manifest = source / 'Cargo.toml'
    os.utime(manifest, ns=(SECONDS[0] * 10**9, SECONDS[0] * 10**9))
    original_stat = manifest.stat()
    env = h.environment(args.private / arm, 'engine', toolchain)
    proof = output / 'build-script-invocations.log'
    cc = Path(shutil.which('cc', path=env.get('PATH')) or '/missing-cc').resolve()
    ar = Path(shutil.which('ar', path=env.get('PATH')) or '/missing-ar').resolve()
    env.update(RA_JIT_DEMAND_STD='1', RA_JIT_STATS='1',
               RA_JIT_MANIFEST_CONTENT_GENERATION='1',
               RA_JIT_WATCHED_MANIFEST_BYTES='0' if arm == 'off' else '1',
               JR_MANIFEST_CC=str(cc), JR_MANIFEST_AR=str(ar),
               JR_MANIFEST_PROOF_LOG=str(proof))
    state = {'scope': __doc__, 'arm': arm, 'status': 'incomplete', 'rows': [],
             'source_before': {name: snapshot(source / name) for name in FILES},
             'environment': dict(sorted(env.items())), 'engine_before': engine_before,
             'toolchain_before': toolchain_identity_before,
             'native_tools_before': {'cc': snapshot(cc, False), 'ar': snapshot(ar, False)},
             'caches_retained': True,
             'oracle_limitation': 'Fixed 2023 input mtimes precede fresh 2026 Cargo fingerprints. A failed OFF control is not uniquely attributable to v76. Strict expected values are never relaxed.'}

    def save():
        m.durable(output / 'state.json', (json.dumps(state, indent=2) + '\n').encode())

    save()
    try:
        for index, seconds in enumerate(SECONDS):
            os.utime(manifest, ns=(seconds * 10**9, seconds * 10**9))
            nonce = uuid.uuid4().hex
            prefix = output / f'{index}-run'
            callenv = dict(env, NATIVE_NONCE=nonce)
            command = h.command(args.engine, 'engine', operation='run', arguments=[])
            before_proof = proof.read_bytes() if proof.exists() else b''
            row = {'index': index, 'mtime_seconds': seconds, 'expected': seconds % 1000,
                   'nonce': nonce, 'manifest_before': snapshot(manifest),
                   'source_before': {name: snapshot(source / name) for name in FILES},
                   'actual_launch': {'argv': command, 'cwd': str(source),
                                     'environment': dict(sorted(callenv.items()))},
                   'script_proof_before_base64': base64.b64encode(before_proof).decode('ascii'),
                   'accepted': False}
            state['rows'].append(row)
            save()
            row['process'] = h.runtime.run_process(command, source, callenv, prefix, args.timeout)
            raw, text, error = m.captured(prefix)
            stdout = prefix.with_suffix('.stdout').read_bytes()
            marker = f'MANIFEST_NATIVE_{nonce}_{seconds % 1000}'
            row.update(raw=raw, raw_error=error, expected_marker=marker,
                       marker_lines=[line for line in stdout.decode(errors='replace').splitlines()
                                     if line.startswith('MANIFEST_NATIVE_')],
                       manifest_after=snapshot(manifest),
                       script_proof_after_base64=base64.b64encode(proof.read_bytes() if proof.exists() else b'').decode('ascii'))
            row['status_receipt'] = h.runtime.run_process(
                [str(args.engine), 'status'], source, env, output / f'{index}-status', 30)
            row['worker_evidence'] = evidence(output, str(index), env)
            target = Path(env['CARGO_TARGET_DIR'])
            row['cargo_evidence'] = [snapshot(path, include_bytes=path.name in ('output', 'invoked.timestamp', 'manifest_native.c'))
                                     for path in sorted(target.rglob('*')) if path.is_file()
                                     and (path.name in ('output', 'invoked.timestamp', 'manifest_native.c', 'libmanifestnative.a')
                                          or '.fingerprint' in path.parts)]
            row['source_bytes_unchanged'] = all((source / name).read_bytes() == data for name, data in FILES.items())
            after_proof = proof.read_bytes() if proof.exists() else b''
            added = after_proof[len(before_proof):] if after_proof.startswith(before_proof) else b''
            row['script_invoked_for_expected_mtime'] = any(
                line.split()[:2] == [str(seconds).encode(), str(seconds % 1000).encode()]
                for line in added.splitlines())
            row['accepted'] = (row['process']['status'] == 0 and not row['process']['timed_out']
                               and not row['process']['error'] and not error
                               and row['marker_lines'] == [marker]
                               and row['source_bytes_unchanged']
                               and row['script_invoked_for_expected_mtime']
                               and row['manifest_before']['mtime_ns'] == seconds * 10**9
                               and row['manifest_after']['mtime_ns'] == seconds * 10**9)
            save()
        state['status'] = 'passed' if all(row['accepted'] for row in state['rows']) else 'failed'
    finally:
        for name, data in FILES.items():
            m.durable(source / name, data)
            initial = state['source_before'][name]
            os.utime(source / name, ns=(initial['atime_ns'], initial['mtime_ns']))
        os.utime(manifest, ns=(original_stat.st_atime_ns, original_stat.st_mtime_ns))
        state['source_after'] = {name: snapshot(source / name) for name in FILES}
        state['source_restored'] = all((source / name).read_bytes() == data for name, data in FILES.items())
        state['manifest_mtime_restored'] = manifest.stat().st_mtime_ns == original_stat.st_mtime_ns
        state['stop'] = h.runtime.run_process([str(args.engine), 'stop'], source, env, output / 'stop', 30)
        state['post_stop_evidence'] = evidence(output, 'post-stop', env)
        state['stop_accepted'] = state['stop']['status'] == 0 and not state['stop']['timed_out'] and not state['stop']['error']
        save()
        state['engine_after'] = snapshot(args.engine, False)
        state['toolchain_after'] = h.toolchain_identity(toolchain)
        state['native_tools_after'] = {'cc': snapshot(cc, False), 'ar': snapshot(ar, False)}
        state['identities_unchanged'] = (state['engine_after']['sha256'] == engine_before['sha256']
            and state['toolchain_after'] == state['toolchain_before']
            and all(state['native_tools_after'][key]['sha256'] == state['native_tools_before'][key]['sha256'] for key in ('cc', 'ar')))
        save()
    return (state['status'] == 'passed' and state['source_restored'] and state['manifest_mtime_restored']
            and state['identities_unchanged'] and state['stop_accepted'])


